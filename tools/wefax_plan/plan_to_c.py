#!/usr/bin/env python3
"""plan.json (this folder) -> src/wefax/plan_default.h, the plan Auto Plan follows when /mnt/wefax/plan.json is absent."""
import json, os

ICI = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(ICI, "plan.json")).read()
json.loads(src)                                     # a broken plan never gets into the firmware
lines = "\n".join('    "%s\\n"' % l.replace("\\", "\\\\").replace('"', '\\"') for l in src.splitlines())
out = os.path.join(ICI, "..", "..", "src", "wefax", "plan_default.h")
open(out, "w").write("/* Generated by tools/wefax_plan/plan_to_c.py from tools/wefax_plan/plan.json: edit that, not this */\n\n"
                     "static const char plan_default_json[] =\n%s;\n" % lines)
print(out)
